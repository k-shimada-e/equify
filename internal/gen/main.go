// Command gen forwards the public API of the pinned testify dependency.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	dir, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "github.com/stretchr/testify").Output()
	must(err)
	for _, pkg := range []string{"assert", "require"} {
		generate(strings.TrimSpace(string(dir)), pkg)
	}
}

func generate(root, pkg string) {
	fset := token.NewFileSet()
	entries, err := os.ReadDir(filepath.Join(root, pkg))
	must(err)
	var decls []string
	skip := map[string]bool{"New": true, "Equal": true, "Equalf": true, "NotEqual": true, "NotEqualf": true, "ObjectsAreEqual": true}
	for _, entry := range entries {
		if !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, filepath.Join(root, pkg, entry.Name()), nil, 0)
		must(err)
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if d.Recv != nil || !ast.IsExported(d.Name.Name) || skip[d.Name.Name] {
					continue
				}
				var sig bytes.Buffer
				must(format.Node(&sig, fset, d.Type))
				var args []string
				for _, field := range d.Type.Params.List {
					for _, name := range field.Names {
						arg := name.Name
						if _, ok := field.Type.(*ast.Ellipsis); ok {
							arg += "..."
						}
						args = append(args, arg)
					}
				}
				ret := ""
				if d.Type.Results != nil {
					ret = "return "
				}
				mark := ""
				if len(args) > 0 && args[0] == "t" {
					mark = "markHelper(t).Helper(); "
				}
				decls = append(decls, "func "+d.Name.Name+strings.TrimPrefix(sig.String(), "func")+" { "+mark+ret+"upstream."+d.Name.Name+"("+strings.Join(args, ", ")+") }")
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					switch s := spec.(type) {
					case *ast.TypeSpec:
						if ast.IsExported(s.Name.Name) && s.Name.Name != "Assertions" {
							decls = append(decls, "type "+s.Name.Name+" = upstream."+s.Name.Name)
						}
					case *ast.ValueSpec:
						for _, name := range s.Names {
							if ast.IsExported(name.Name) {
								decls = append(decls, d.Tok.String()+" "+name.Name+" = upstream."+name.Name)
							}
						}
					}
				}
			}
		}
	}
	sort.Strings(decls)
	imports := "upstream \"github.com/stretchr/testify/" + pkg + "\"; \"time\"; \"net/http\"; \"net/url\";"
	if pkg == "require" {
		imports += " assert \"github.com/stretchr/testify/assert\";"
	}
	src := "// Code generated by go generate; DO NOT EDIT.\npackage " + pkg + "\nimport (" + imports + ")\n" + strings.Join(decls, "\n")
	out, err := format.Source([]byte(src))
	must(err)
	must(os.MkdirAll(pkg, 0755))
	path := filepath.Join(pkg, "forward.go")
	must(os.WriteFile(path, out, 0644))
}

func must(err error) {
	if err != nil {
		panic(fmt.Sprint(err))
	}
}
