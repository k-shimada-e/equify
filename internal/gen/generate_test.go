package main

import (
	"bytes"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestGeneratePublicAPI(t *testing.T) {
	root := t.TempDir()
	for _, pkg := range []string{"assert", "require"} {
		dir := filepath.Join(root, pkg)
		must(os.MkdirAll(dir, 0755))
		must(os.WriteFile(filepath.Join(dir, "api.go"), []byte(`package `+pkg+`
type TestingT interface { Errorf(string, ...interface{}) }
type Assertions struct{}
type hidden struct{}
const PublicConstant = 1
var PublicVariable = 2
func New(t TestingT) *Assertions { return nil }
func Equal(t TestingT, expected, actual interface{}, msgAndArgs ...interface{}) bool { return true }
func Equalf(t TestingT, expected, actual interface{}, msg string, args ...interface{}) bool { return true }
func NotEqual(t TestingT, expected, actual interface{}, msgAndArgs ...interface{}) bool { return true }
func NotEqualf(t TestingT, expected, actual interface{}, msg string, args ...interface{}) bool { return true }
func ObjectsAreEqual(expected, actual interface{}) bool { return true }
func Check(t TestingT, value interface{}, msgAndArgs ...interface{}) bool { return true }
func Stop(t TestingT, msgAndArgs ...interface{}) {}
func Inspect(value interface{}) bool { return true }
func hiddenFunc() {}
func (a *Assertions) MethodOnly() {}
`), 0644))
		must(os.WriteFile(filepath.Join(dir, "extra.go"), []byte("package "+pkg+"\nfunc Extra() {}\n"), 0644))
		must(os.WriteFile(filepath.Join(dir, "api_test.go"), []byte("package "+pkg+"\nfunc TestOnly() {}\n"), 0644))
	}

	// generate writes relative to the working directory. Keep this test serial.
	previous, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(t.TempDir()); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := os.Chdir(previous); err != nil {
			t.Error(err)
		}
	})

	for _, pkg := range []string{"assert", "require"} {
		t.Run(pkg, func(t *testing.T) {
			generate(root, pkg)
			path := filepath.Join(pkg, "forward.go")
			first, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			formatted, err := format.Source(first)
			if err != nil || !bytes.Equal(first, formatted) {
				t.Fatalf("generated source is not valid gofmt output: %v", err)
			}
			text := string(first)
			for _, want := range []string{
				"// Code generated by go generate; DO NOT EDIT.",
				"package " + pkg,
				"type TestingT = upstream.TestingT",
				"const PublicConstant = upstream.PublicConstant",
				"var PublicVariable = upstream.PublicVariable",
				"return upstream.Check(t, value, msgAndArgs...)",
				"upstream.Stop(t, msgAndArgs...)",
				"return upstream.Inspect(value)",
				"upstream.Extra()",
			} {
				if !strings.Contains(text, want) {
					t.Errorf("missing %q in generated source", want)
				}
			}
			for _, unwanted := range []string{
				"func New(", "func Equal(", "func Equalf(", "func NotEqual(",
				"func NotEqualf(", "func ObjectsAreEqual(", "type Assertions",
				"hidden", "MethodOnly", "TestOnly",
			} {
				if strings.Contains(text, unwanted) {
					t.Errorf("unexpected declaration %q", unwanted)
				}
			}
			if got := strings.Count(text, "markHelper(t).Helper()"); got != 2 {
				t.Errorf("helper markers=%d, want 2 for TestingT functions only", got)
			}
			generate(root, pkg)
			second, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(first, second) {
				t.Fatalf("regeneration is not deterministic: %v", err)
			}
		})
	}
}
